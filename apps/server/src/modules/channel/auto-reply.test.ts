import { describe, expect, it } from 'vitest';
import { isAutoReply } from './auto-reply';

/*
 * 我方发出的自动回复（PRD R-SL-08、AC-P1-03，待办 16）：带 Auto-Submitted（RFC 3834）或常见的自动回复标记的邮件不算回复。
 * 头字段按入库时的写法：小写名 + 原值（channel.message.headers）。
 */

const headers = (entries: Record<string, string>) =>
  Object.entries(entries).map(([key, value]) => ({ key, value }));

describe('自动回复标记', () => {
  it('Auto-Submitted 为 auto-replied、auto-generated 等（不分大小写、可带参数）算自动回复', () => {
    expect(isAutoReply(headers({ 'auto-submitted': 'auto-replied' }))).toBe(true);
    expect(isAutoReply(headers({ 'auto-submitted': 'Auto-Generated' }))).toBe(true);
    expect(isAutoReply(headers({ 'auto-submitted': 'auto-replied; owner-email="a@b.com"' }))).toBe(
      true,
    );
  });

  it('Auto-Submitted: no 是人写的邮件（RFC 3834），不算', () => {
    expect(isAutoReply(headers({ 'auto-submitted': 'no' }))).toBe(false);
    expect(isAutoReply(headers({ 'auto-submitted': ' NO ' }))).toBe(false);
  });

  it('X-Autoreply、X-Autorespond、X-Autogenerated 与 Precedence: auto_reply 也算', () => {
    expect(isAutoReply(headers({ 'x-autoreply': 'yes' }))).toBe(true);
    expect(isAutoReply(headers({ 'x-autorespond': 'Out of office' }))).toBe(true);
    expect(isAutoReply(headers({ 'x-autogenerated': 'Reply' }))).toBe(true);
    expect(isAutoReply(headers({ precedence: 'auto_reply' }))).toBe(true);
  });

  it('普通的回信（只有 In-Reply-To 等）、群发的 Precedence: bulk 不算自动回复', () => {
    expect(
      isAutoReply(headers({ 'in-reply-to': '<a@b>', references: '<a@b>', subject: 'Re: hi' })),
    ).toBe(false);
    expect(isAutoReply(headers({ precedence: 'bulk' }))).toBe(false);
    expect(isAutoReply([])).toBe(false);
  });
});
